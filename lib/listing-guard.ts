/**
 * 타이틀 기반 REJECT 레이어.
 *
 * mallName으로는 잡을 수 없는 경우가 있다. 대표적으로 네이버 "가격비교" 풀은
 * mallName이 "네이버"로만 뜨는데, 내부에는 수백 개 개별 셀러가 섞여 있고
 * 상당수가 중국어 원문을 MT로 돌린 저품질 드랍쉬핑 리스팅이다.
 *
 * 이들은 타이틀에서 반복적으로 특정 패턴을 남긴다:
 *  - "하이 스트리트 패션 2026 최신…"       (high street 직역)
 *  - "슬림 피팅 하운드투스 트위드 블레이…" (fit 직역 + 키워드 스터핑)
 *  - "여성청 자켓"                                (번역 오류)
 *  - 명품 벨트 "교체용 29mm 가죽끈"         (정품이 아닌 대체품)
 *
 * 이 레이어는 sanitize된 타이틀을 보고 위 시그널을 하나라도 찾으면 상품을 drop한다.
 * 단 BOOST 몰(파페치·네타포르테 등)에서 온 상품은 번역 톤이 독특할 수 있으므로
 * 호출자(api.ts)가 `isBoostedMall`을 먼저 확인하고 건너뛴다.
 */

const REJECT_TITLE_PATTERNS: readonly RegExp[] = [
  // 중국어 원문을 그대로 직역한 전형적 토큰
  /하이\s*스트리트/i,
  /\b슬림\s*피팅\b/i,
  /여성청\s*자켓/, // "여성 데님 자켓"이 MT 오류로 이렇게 나옴
  /\b스트\s*라스\b/i, // "스트라스" 장식 — MT 튐

  // 키워드 스터핑: 디자이너 재킷 + 연도 + "패션 최신" 형태
  /디자이너\s*재킷[^.]{0,30}(?:2023|2024|2025|2026)\s*(?:최신|패션|신상)/i,
  /\b최신\s*디자이너\s*재킷\b/i,

  // 명품 "호환/교체용" 대체품 스팸 (가죽 벨트 교체 끈 전문몰이 주로 생산)
  /명품\s*호환/,
  /교체용\s*(?:벨트|가죽|혁띠|혁대|끈)/,
  /(?:벨트|혁띠|혁대)[^.]{0,30}\b(?:29|31|32|33|34|35)\s*mm\b/i,
  /\b자동\s*버클\b.*\b혁[띠대]\b/,

  // 핸드메이드 에코백 / 빅사이즈 88 66 77 같이 드랍쉬핑 타이틀 전형
  /핸드메이드\s*에코\s*백/,
  /\b(?:55|66|77|88)\s*(?:55|66|77|88)\s*(?:55|66|77|88)\b/,

  // 중국어 직역 MT 시그널 (네이버 가격비교 풀 안에서 발견된 고신뢰 패턴)
  /가짜\s*가죽/, // 假皮 직역, 한국어는 "인조가죽"
  /새로운\s*모든\s*경기/, // "new all-match" 오역
  /투피스\s*대용/, // "two-piece alternative" 오역
  /짧은\s*실루엣/, // 어색한 번역체
  /\b가짜\s*(?:레더|가죽)\b/,
  /여성용\s+세련된\s+슬림/, // MT 전형 어순
];

export function looksLikeRejectListing(sanitizedTitle: string): boolean {
  if (!sanitizedTitle) return true;
  return REJECT_TITLE_PATTERNS.some((pattern) => pattern.test(sanitizedTitle));
}
